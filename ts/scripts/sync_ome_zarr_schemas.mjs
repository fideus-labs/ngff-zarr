// Write src/schemas/ome_zarr_json_schemas.ts from the official OME-Zarr JSON
// Schemas the Python package bundles under py/ngff_zarr/spec, and
// src/schemas/ngff_rules.ts from its rule table py/ngff_zarr/rules.json, so
// both ports validate against the same files. Run from ts/:
//   node scripts/sync_ome_zarr_schemas.mjs && npm run fmt
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const spec = join("..", "py", "ngff_zarr", "spec");
const trees = {};
for (const version of readdirSync(spec).sort()) {
  const directory = join(spec, version, "schemas");
  let names;
  try {
    names = readdirSync(directory).filter((name) => name.endsWith(".schema"));
  } catch {
    continue;
  }
  trees[version] = names
    .sort()
    .map((name) => JSON.parse(readFileSync(join(directory, name), "utf8")));
}

writeFileSync(
  join("src", "schemas", "ome_zarr_json_schemas.ts"),
  `// Generated by scripts/sync_ome_zarr_schemas.mjs from py/ngff_zarr/spec.
// Do not edit: run the script after the bundled schemas change.
// The official OME-Zarr JSON Schemas, one list per bundled version tree.
export const OME_ZARR_JSON_SCHEMAS: Record<
  string,
  ReadonlyArray<Record<string, unknown>>
> = JSON.parse(${JSON.stringify(JSON.stringify(trees))});
`,
);

writeFileSync(
  join("src", "schemas", "ngff_rules.ts"),
  `// Generated by scripts/sync_ome_zarr_schemas.mjs from py/ngff_zarr/rules.json.
// Do not edit: run the script after the rule table changes.
// The rules of the OME-Zarr specification checked beyond the JSON Schemas:
// each rule's code and the versions whose text states it.
export interface NgffRule {
  code: string;
  versions: string[];
}

export const NGFF_RULES: ReadonlyArray<NgffRule> = ${JSON.stringify(
    JSON.parse(
      readFileSync(join("..", "py", "ngff_zarr", "rules.json"), "utf8"),
    ).map(({ code, versions }) => ({ code, versions })),
  )};
`,
);
